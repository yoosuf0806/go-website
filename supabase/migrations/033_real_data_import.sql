-- 033_real_data_import.sql
--
-- Replaces the earlier dummy/placeholder ops data with the real business data
-- from the founder's spreadsheet (golden_oven_statement.xlsx). Website `orders`
-- (the storefront's live table) were test/dummy orders used to build the site,
-- NOT real sales -- this migration does not touch that table; it only affects
-- ops_sales / ops_purchases / ops_ad_spend.
--
-- What changes vs. migration 030:
--   * 030 seeded only coarse MONTHLY TOTALS for B2C sales and purchasing
--     (sourced from the "T accounts" ledger, Mar-Jul 2026), and a partial
--     B2B log (Jan-Feb 2026 only, from the "sales b2b" sheet).
--   * This migration replaces those with the FULL per-order / per-purchase
--     detail from the "sales b2c", "sales b2b" and "Purchasing" sheets:
--       - B2C: 383 individual orders, Apr 2025 - Aug 2026 (in progress)
--       - B2B: 64 individual orders, Jan - Aug 2026 (in progress)
--       - Purchasing: 104 individual purchase line items, Mar - Jul 2026
--     Every inserted row is tagged note = 'real data import' so a re-run of
--     this migration is idempotent (it deletes its own prior output first).
--
-- Data-quality notes (the source spreadsheet has some internal drift; these
-- are deliberate choices, not parsing bugs):
--   * B2C: April/May 2025 rows have no per-order date in the sheet (dating
--     wasn't tracked yet) -- defaulted to the 15th of that month.
--   * Excel date-transposition: some cells stored as native Excel dates (not
--     typed text) had day/month silently swapped by Excel on entry (e.g. a
--     cell under the "August" section read as 8 November). Detected by
--     cross-checking every date's month against its own section header and
--     corrected by swapping day/month back (17 rows across B2C/B2B).
--   * B2C Jan/Feb 2026 and Purchasing March 2026: the sheet's own hand-typed
--     month-end "total" is off by a small amount from the sum of its own line
--     items (e.g. March purchasing: typed total 55,945 vs line-item sum
--     57,705). The line-item sum is used -- it is the more granular, directly
--     verifiable figure.
--   * Ad spend: this workbook's "Sales summary" tab has two ad-spend rows
--     ("Total LKR" vs "FB Advertisement"/"TikTok Ads") that disagree for
--     several months. The FB/TikTok breakdown is used (it is what the
--     workbook's own Net Profit row is actually computed from), falling back
--     to "Total LKR" only where that breakdown is blank (August 2025).
--     March-July 2026 ad spend is UNCHANGED from migration 030 (it came from
--     the more granular "T accounts" ledger, a better source than this tab's
--     monthly rollup, and is not touched here).
--
-- Idempotent: safe to re-run (deletes prior output of this migration first).

